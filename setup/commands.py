"""Registers on Telegram the command menu (`setMyCommands`) and the bot's description
(`setMyDescription`, `setMyShortDescription`), in English and Italian, or shows them.

Usage:
  uv run python setup/commands.py          # registers the commands and descriptions below
  uv run python setup/commands.py --info   # shows the registered ones

Uses TELEGRAM_BOT_TOKEN from `.env` (the test or the production bot, depending on the token).
Never prints the token. The commands must be those handled in `bot/src/bot.ts`.
"""

import argparse

from webhook import call

from core.config import load_env

ITALIAN_COMMANDS = [
    {"command": "avvisi", "description": "Gli avvisi del corso ancora validi"},
    {"command": "eventi", "description": "Seminari e attività che danno CFU"},
    {"command": "novita", "description": "Cosa è cambiato sul sito del corso di recente"},
    {"command": "fonti", "description": "Da dove vengono le informazioni e quando sono aggiornate"},
    {"command": "start", "description": "Cosa fa il bot (non ufficiale)"},
]
# Same rule as the bot's texts (`language` in bot/src/bot.ts): Italian for apps in Italian,
# English for everyone else (default menu, without `language_code`).
COMMANDS = [  # English names: the bot maps the Italian ones to these (`ITALIAN_COMMANDS` in bot.ts)
    {"command": "notices", "description": "Course notices that are still valid"},
    {"command": "events", "description": "Seminars and activities that give credits"},
    {"command": "updates", "description": "What changed on the course website recently"},
    {"command": "sources", "description": "Where the information comes from and when it's updated"},
    {"command": "start", "description": "What the bot does (unofficial)"},
]
MENU = [(COMMANDS, None), (ITALIAN_COMMANDS, "it")]  # (commands, language_code)

# Description (empty chat, before "Start"; at most 512 characters) and short description (profile
# and sharing; at most 120), with the same language rule as the menu.
DESCRIPTIONS = {
    None: (
        "UNOFFICIAL bot, not affiliated with the University of Cagliari. It answers questions"
        " about the Master's degree in Computer Science (study plans, exams, deadlines, "
        "graduation, timetables) using only the public pages and documents of the course, and"
        " always cites its sources. Answers are generated by an artificial intelligence model"
        " and may contain errors: when in doubt, the official website prevails. Your messages"
        " are not stored.",
        "Unofficial bot on the Master's in Computer Science at the University of Cagliari, "
        "with sources.",
    ),
    "it": (
        "Bot NON ufficiale, non affiliato all'Università di Cagliari. Risponde alle domande "
        "sulla laurea magistrale in Informatica (piano di studi, esami, scadenze, laurea, "
        "orari) usando solo le pagine e i documenti pubblici del corso, e cita sempre le "
        "fonti. Le risposte sono generate da un modello di intelligenza artificiale e possono"
        " contenere errori: in caso di dubbio vale il sito ufficiale. I tuoi messaggi non "
        "vengono salvati.",
        "Bot non ufficiale sulla magistrale in Informatica dell'Università di Cagliari, con "
        "le fonti.",
    ),
}


def main() -> None:
    args = argparse.ArgumentParser(description="The bot's command menu on Telegram")
    args.add_argument("--info", action="store_true", help="only show the registered commands")
    a = args.parse_args()
    load_env()
    for commands, code in MENU:
        language = {"language_code": code} if code else {}
        if not a.info:
            call("setMyCommands", {"commands": commands, **language})
        print(f"\nMenu {'default (English)' if code is None else code}:")
        for c in call("getMyCommands", language):
            print(f"/{c['command']:8} {c['description']}")
        long, short = DESCRIPTIONS[code]
        if not a.info:
            call("setMyDescription", {"description": long, **language})
            call("setMyShortDescription", {"short_description": short, **language})
        print("Description:", call("getMyDescription", language)["description"])
        print("Short:", call("getMyShortDescription", language)["short_description"])


if __name__ == "__main__":
    main()
